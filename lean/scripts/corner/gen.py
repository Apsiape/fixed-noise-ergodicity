# Untrusted certificate producer for the corner lemma (thr:corner) on the box V_6.
# Input: the letter table dumped from Lean by scripts/corner/Dump.lean (order of
# `Letter.letters`, colour codes `Letter.codeN/E/S/W`). Output: the Lean data file
# FixedNoiseErgodicity/Three/CornerData.lean (definitions only). Nothing here is trusted:
# every literal is checked in the kernel by FixedNoiseErgodicity/Three/Corner*.lean.
# Usage: source scripts/env.sh; lean scripts/corner/Dump.lean > LETTERS.txt
#        python -I -B scripts/corner/gen.py LETTERS.txt FixedNoiseErgodicity/Three/CornerData.lean
# Before writing, the generator replays its updates through a Python replica of the Lean checker
# (`replica`); the Lean kernel check in Three/Corner.lean is the one that counts.
import sys
sys.path.insert(0, __import__('os').path.dirname(__file__))
from analyze import L, thin, thick, b1, b2, cls, root_idx, run, mask, supp, VEC

R = 6
N = 2 * R + 1
out = []
w = out.append
w('/-')
w('# Data of the corner-lemma certificate (generated; untrusted until checked)')
w('')
w('Generated by `scripts/corner/gen.py` from the letter table that `scripts/corner/Dump.lean`')
w('prints (the order of `Letter.letters` and the codes `Letter.codeN/E/S/W`). Nothing in this')
w('file is trusted: the class tables and the masks of `𝒟_κ` are checked against their definitions')
w('in `Three/CornerTables.lean`, and the rounds are checked by the kernel in `Three/Corner.lean`.')
w('')
w('* `clsN`, `clsE`, `clsS`, `clsW`: the 64 colour-class masks of each side (`classMask`).')
w('* `dMaskA`, …: the letters of `𝔸` of one thin type, without the four corner letters with')
w('  bit `0`; `rootIdx κ`: the index of `(a, κ, A, 1, 1)` in `Letter.letters`.')
w('* `ups κ`: the updates `(j, e, m)` of the certificate on `V_6` (sites in raster order, index')
w('  `13 (y + 6) + (x + 6)`): replace the mask at `j` by `m`, justified by the support in')
w('  direction `e`. They delete the dependency cone of the root in a synchronous')
w('  arc-consistency run, round by round; the last update deletes the root.')
w('-/')
w('')
w('import FixedNoiseErgodicity.Scaffold.Format')
w('')
w('set_option autoImplicit false')
w('')
w('namespace FNE.Three')
w('')
def lst(xs, ind='  '):
    return '[' + (',\n' + ind).join(str(x) for x in xs) + ']'
for s in 'NESW':
    w('/-- The colour-class masks of side `%s` (codes `0, …, 63`). -/' % s)
    w('def cls%s : List ℕ :=\n  %s\n' % (s, lst(cls[s][c] for c in range(64))))
def zc(i): return thin[i] == 'a' and thick[i][0] == 'C' and b1[i] == 0 and b2[i] == 0
for th in 'abcd':
    m = mask(lambda i: thin[i] == th and not zc(i))
    w('/-- The letters of thin type `%s`, without the corner letters with bit `0`. -/' % th)
    w('def dMask%s : ℕ := %d\n' % (th.upper(), m))
w('/-- The index of the root `(a, κ, A, 1, 1)` in `Letter.letters`. -/')
w('def rootIdx : FNE.Scaffold.Corner → ℕ')
w('  ' + ' '.join('| .%s => %d' % (k, root_idx(k)) for k in 'abcd') + '\n')
DIRS = {'e1': 'e1', 'e1p': "e1'", 'e2': 'e2', 'e2p': "e2'"}
def jx(s): return (s[1] + R) * N + (s[0] + R)
def cone_updates(k):
    """Sequential single-direction updates deleting the root's dependency cone."""
    sites, hist = run(k, R)
    T = len(hist) - 1
    delr = {}
    for t in range(1, T + 1):
        for s in sites:
            gone = hist[t - 1][s] & ~hist[t][s]
            for i in range(276):
                if (gone >> i) & 1: delr[(s, i)] = t
    def why(s, i, t):
        for d, (dx, dy) in VEC.items():
            n = (s[0] + dx, s[1] + dy)
            if n in hist[0] and not (supp(d, hist[t - 1][n]) >> i) & 1: return d, n
        raise Exception('no direction')
    root = ((0, 0), root_idx(k))
    need = {}; stack = [root]
    while stack:
        e = stack.pop()
        if e in need: continue
        s, i = e; t = delr[e]; d, n = why(s, i, t); need[e] = (t, d)
        for i2 in range(276):
            if (hist[0][n] >> i2) & 1 and (supp(d, 1 << i2) >> i) & 1:
                assert delr[(n, i2)] < t
                stack.append((n, i2))
    groups = {}
    for (s, i), (t, d) in need.items():
        groups.setdefault((t, jx(s), d), 0)
        groups[(t, jx(s), d)] |= 1 << i
    cur = [hist[0][s] for s in sorted(sites, key=jx)]
    ups = []
    for (t, j, d) in sorted(groups):
        cur[j] &= ~groups[(t, j, d)]
        ups.append((j, d, cur[j]))
    return ups, len(need)
NBR = {'e1': lambda j: j + 1 if j % N < N - 1 else None, 'e1p': lambda j: j - 1 if j % N > 0 else None,
       'e2': lambda j: j + N if j < N * (N - 1) else None, 'e2p': lambda j: j - N if j >= N else None}
def replica(k, ups):
    """The Lean checker, replicated: init, then each update checked against the current state."""
    def dm(th): return mask(lambda i: thin[i] == th and not zc(i))
    st = []
    for j in range(N * N):
        x, y = j % N, j // N
        st.append(1 << root_idx(k) if j == (N * N) // 2 else dm({(0, 0): 'a', (1, 0): 'c', (0, 1): 'd', (1, 1): 'b'}[(x % 2, y % 2)]))
    for (j, d, m) in ups:
        n = NBR[d](j)
        assert n is not None
        x = st[j] & supp(d, st[n])
        assert x & m == x, ('rejected', j, d)
        st[j] = m
    assert not (st[(N * N) // 2] >> root_idx(k)) & 1
for k in 'abcd':
    ups, nneed = cone_updates(k)
    replica(k, ups)
    w('/-- The updates for the corner `∠%s` (%d updates, deleting %d entries). -/' % (k, len(ups), nneed))
    w('def ups%s : List (ℕ × FNE.Scaffold.Dir × ℕ) :=' % k.upper())
    w('  [' + (',' + chr(10) + '   ').join('(%d, .%s, %d)' % (j, DIRS[d], m) for (j, d, m) in ups) + ']' + chr(10))
    print(k, 'updates', len(ups), 'cone', nneed)
w('/-- The updates, by corner. -/')
w('def ups : FNE.Scaffold.Corner → List (ℕ × FNE.Scaffold.Dir × ℕ)')
w('  ' + ' '.join('| .%s => ups%s' % (k, k.upper()) for k in 'abcd') + chr(10))
w('end FNE.Three')
open(sys.argv[2], 'w', newline='\n', encoding='utf-8').write('\n'.join(out) + '\n')
print('written', sys.argv[2])
