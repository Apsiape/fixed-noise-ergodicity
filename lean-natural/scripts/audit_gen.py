"""Regenerate ForgettingNaturalRule/Audit.lean (run on Windows with `python -I -B scripts/audit_gen.py`).

Every `theorem` of the modules below (in dependency order) gets an `#audit_axioms_strict` line; the
final targets are also printed with `#print axioms`; `#audit_prefix FNR` checks every project
declaration. Namespaces are tracked from `namespace X` / `end X` lines (sections are ignored).
"""
from pathlib import Path
import re

P = Path(__file__).resolve().parents[1]
MODULES = ['Constants', 'Rule/Local', 'Rule/Bridge', 'Coherence/Rel', 'Coherence/Tiling',
           'Forget/Paths', 'Forget/Unique', 'Memory/Cover', 'Memory/Branch', 'PCA/Average',
           'Memory/Invariant', 'Main', 'Reduction']
# The release targets first (session 3), then the other final theorems of the development.
TARGETS = ['FNR.natural_classification', 'FNR.theorem_A', 'FNR.machine_corollary',
           'FNR.domino_reduction', 'FNR.domino_undecidable',
           'FNR.theorem_A_from_domino', 'FNR.theorem_A_undecidable', 'FNR.ergodicity_reduction',
           'FNR.ergodicity_undecidable']
NS = re.compile(r'^namespace\s+([\w.]+)\s*$')
END = re.compile(r'^end\s+([\w.]+)\s*$')
SEC = re.compile(r'^section(\s+[\w.]+)?\s*$')
THM = re.compile(r'^(?:@\[[^\]]*\]\s*)?(?:protected\s+)?theorem\s+([^\s:(\[{]+)')

HEADER = '''/-
# Axiom audit

Built by `scripts/audit.sh` (its log is copied to `AXIOMS.txt`); generated by
`scripts/audit_gen.py`.
* The final targets are printed with `#print axioms` and audited with `#audit_axioms_strict`.
* Every theorem of the development is audited with `#audit_axioms_strict`: only `propext`,
  `Classical.choice` and `Quot.sound` are allowed, and `sorryAx` is an error.
* `#audit_prefix FNR` checks every declaration of the project (including private and
  generated ones) and lists those depending on `sorryAx`.
* The audit command is the noise-diagram core's `UND.Audit` (REUSE).
-/
import ForgettingNaturalRule
import UncomputableNoiseDiagram.AuditCommand

set_option autoImplicit false

/-! ## Final targets -/

'''


def theorems(path):
    stack, out = [], []
    for line in path.read_text(encoding='utf-8').splitlines():
        m = NS.match(line)
        if m:
            stack.append(m.group(1)); continue
        if SEC.match(line):
            stack.append(None); continue
        if (END.match(line) or line.strip() == 'end') and stack:
            stack.pop(); continue
        m = THM.match(line)
        if m:
            ns = '.'.join(s for s in stack if s)
            out.append(f'{ns}.{m.group(1)}' if ns else m.group(1))
    return out


def main():
    text = HEADER
    for t in TARGETS:
        text += f'#print axioms {t}\n#audit_axioms_strict {t}\n'
    text += '\n/-! ## Every theorem (strict) -/\n'
    for mod in MODULES:
        text += f'\n-- {mod}.lean\n'
        for name in theorems(P / 'ForgettingNaturalRule' / (mod + '.lean')):
            text += f'#audit_axioms_strict {name}\n'
    text += '\n/-! ## Every project declaration -/\n\n#audit_prefix FNR\n'
    with open(P / 'ForgettingNaturalRule' / 'Audit.lean', 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote Audit.lean')


if __name__ == '__main__':
    main()
